using System.Text.RegularExpressions;
using Markdig;
using Markdig.Extensions.Tables;
using Markdig.Renderers.Html;
using Markdig.Syntax;
using Markdig.Syntax.Inlines;

namespace Graft.Server;

/// <summary>Rendered README output, plus whether the page needs the diagram renderer loaded.</summary>
public sealed record RenderedMarkdown(string Html, bool HasDiagrams);

/// <summary>
/// Renders a repository's README to HTML.
///
/// <para>
/// This is the one place Graft turns repository content into markup rather than text, so it is the one place
/// a stored cross-site scripting bug could live. Three things keep that closed, in order:
/// </para>
///
/// <para>
/// First, the parser is configured with <c>DisableHtml</c>, so raw HTML in the source is escaped as text
/// instead of being parsed. Every element in the output is therefore generated by Markdig, never copied from
/// the document, which removes the entire class of injected-tag attacks before anything else runs.
/// </para>
///
/// <para>
/// Second, the remaining attacker-controlled values are link and image destinations, and those are checked on
/// the parsed tree while they are still structured data rather than after they have been flattened into a
/// string. Checking the tree is why this does not need a general HTML sanitiser: re-parsing generated markup
/// to find dangerous attributes is strictly harder than never letting a dangerous value reach the renderer.
/// </para>
///
/// <para>
/// Third, <see cref="Render"/> scans its own output and fails closed. That check should never fire; it exists
/// so that a future parser upgrade which changes the output shape degrades to plain text rather than silently
/// becoming an injection point.
/// </para>
/// </summary>
public static partial class MarkdownContent
{
    /// <summary>Largest README rendered. Beyond this the file is shown as plain text instead.</summary>
    public const int MaximumBytes = 512 * 1024;

    /// <summary>Filenames treated as a project's README, in the order they are preferred.</summary>
    public static readonly string[] Names = ["README.md", "readme.md", "Readme.md", "README.markdown", "README"];

    private static readonly MarkdownPipeline Pipeline = new MarkdownPipelineBuilder()
        .UsePipeTables()
        .UseGridTables()
        .UseTaskLists()
        .UseFootnotes()
        .UseAutoLinks()
        .UseEmphasisExtras()
        .UseDefinitionLists()
        .UseAutoIdentifiers()
        .DisableHtml()
        .Build();

    /// <summary>
    /// Renders markdown to HTML. <paramref name="resolveImage"/> maps a repository-relative path to a URL
    /// this server will serve, and returns null when the path cannot be resolved; an image it cannot resolve,
    /// or one pointing off-site, is downgraded to a link rather than fetched.
    /// </summary>
    public static RenderedMarkdown Render(string source, Func<string, string?> resolveImage)
    {
        ArgumentNullException.ThrowIfNull(source);
        ArgumentNullException.ThrowIfNull(resolveImage);

        MarkdownDocument document = Markdig.Markdown.Parse(source, Pipeline);
        foreach (LinkInline link in document.Descendants<LinkInline>())
        {
            if (link.IsImage) RewriteImage(link, resolveImage);
            else RewriteLink(link);
        }

        // Angle-bracket autolinks are a separate node type, not a LinkInline, so they need handling of their
        // own. Missing them would leave <javascript:alert(1)> rendering as a live href, and would leave an
        // ordinary <https://example.com> without the attributes that stop a click leaking a referrer.
        foreach (AutolinkInline autolink in document.Descendants<AutolinkInline>().ToArray())
            RewriteAutolink(autolink);

        foreach (Table table in document.Descendants<Table>()) RewriteTable(table);

        bool diagrams = document.Descendants<FencedCodeBlock>()
            .Any(block => string.Equals(block.Info, "mermaid", StringComparison.OrdinalIgnoreCase));

        string html = Markdig.Markdown.ToHtml(document, Pipeline);
        return IsClean(html) ? new(html, diagrams) : new(Escape(source), false);
    }

    /// <summary>
    /// An image either comes from this repository or it does not load. Graft's policy already blocks
    /// off-site images, and proxying them the way a public forge does would mean this server fetching
    /// attacker-chosen URLs, which on a private network is a request-forgery tool rather than a privacy fix.
    /// Not fetching leaks nothing at all, so there is no referrer to strip.
    /// </summary>
    private static void RewriteImage(LinkInline image, Func<string, string?> resolveImage)
    {
        string? resolved = IsRepositoryRelative(image.Url) ? resolveImage(image.Url!) : null;
        if (resolved is not null)
        {
            image.Url = resolved;
            return;
        }

        // Downgrade to a link so the reader can still see what was referenced and follow it deliberately,
        // rather than being shown a broken image icon with no explanation.
        string? original = image.Url;
        image.IsImage = false;
        image.Url = IsSafeScheme(original) ? original : null;
        if (image.FirstChild is null) image.AppendChild(new LiteralInline(original ?? "image"));
        image.GetAttributes().AddClass("external-image");
        RewriteLink(image);
    }

    /// <summary>
    /// Keeps only schemes a browser will not execute, and marks anything leaving the site so a click does not
    /// hand the destination a referrer or a usable window handle.
    /// </summary>
    private static void RewriteLink(LinkInline link)
    {
        if (!IsSafeScheme(link.Url))
        {
            link.Url = null;
            return;
        }
        if (IsRepositoryRelative(link.Url) || link.Url!.StartsWith('#')) return;
        HtmlAttributes attributes = link.GetAttributes();
        attributes.AddPropertyIfNotExist("rel", "noopener noreferrer nofollow");
        attributes.AddPropertyIfNotExist("target", "_blank");
    }

    /// <summary>
    /// Moves a table's column alignment and width from inline style attributes onto classes.
    ///
    /// <para>
    /// Markdig writes alignment as <c>style="text-align: center;"</c> and grid-table widths as a
    /// <c>&lt;col style="width:…"&gt;</c>. Graft's policy sets <c>style-src 'self'</c>, so a browser refuses
    /// every one of those and the table loses its alignment silently. Relaxing the policy to admit inline
    /// styles is the one thing that must not happen on the page that renders somebody else's repository
    /// content, so the alignment is carried by a class that the stylesheet already knows instead.
    /// </para>
    /// </summary>
    private static void RewriteTable(Table table)
    {
        foreach (TableRow row in table.OfType<TableRow>())
        {
            int position = 0;
            foreach (TableCell cell in row.OfType<TableCell>())
            {
                int column = cell.ColumnIndex >= 0 ? cell.ColumnIndex : position;
                position++;
                if (column >= table.ColumnDefinitions.Count) continue;
                string? alignment = table.ColumnDefinitions[column].Alignment switch
                {
                    TableColumnAlign.Left => "align-left",
                    TableColumnAlign.Center => "align-centre",
                    TableColumnAlign.Right => "align-right",
                    _ => null
                };
                if (alignment is not null) cell.GetAttributes().AddClass(alignment);
            }
        }

        // Clearing these is what stops the renderer writing the style attributes in the first place.
        foreach (TableColumnDefinition definition in table.ColumnDefinitions)
        {
            definition.Alignment = null;
            definition.Width = 0;
        }
    }

    /// <summary>
    /// An autolink carries its destination as its own text, so an unsafe one cannot simply have the
    /// destination blanked the way a titled link can — that would leave the text behind with nothing to say
    /// where it went. It is replaced by that text instead, which renders escaped and inert.
    /// </summary>
    private static void RewriteAutolink(AutolinkInline autolink)
    {
        // An email autolink is rendered as a mailto: address by the renderer, never as an arbitrary scheme.
        if (!autolink.IsEmail && !IsSafeScheme(autolink.Url))
        {
            autolink.ReplaceBy(new LiteralInline(autolink.Url));
            return;
        }
        HtmlAttributes attributes = autolink.GetAttributes();
        attributes.AddPropertyIfNotExist("rel", "noopener noreferrer nofollow");
        attributes.AddPropertyIfNotExist("target", "_blank");
    }

    /// <summary>True for http and https and in-document anchors only. Everything else, including
    /// <c>javascript:</c>, <c>data:</c> and <c>vbscript:</c>, is dropped rather than escaped.</summary>
    private static bool IsSafeScheme(string? url)
    {
        if (string.IsNullOrWhiteSpace(url)) return false;
        if (url.StartsWith('#')) return true;
        if (IsRepositoryRelative(url)) return true;
        return url.StartsWith("http://", StringComparison.OrdinalIgnoreCase)
            || url.StartsWith("https://", StringComparison.OrdinalIgnoreCase)
            || url.StartsWith("mailto:", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// A path inside the repository: no scheme, no protocol-relative prefix and no leading slash. Control
    /// characters are refused because a browser strips some of them before matching a scheme, which is how
    /// values like "java\0script:" get past naive prefix checks.
    /// </summary>
    private static bool IsRepositoryRelative(string? url)
    {
        if (string.IsNullOrWhiteSpace(url)) return false;
        if (url.Any(value => value < 0x20 || value == 0x7f)) return false;
        if (url.StartsWith('#') || url.StartsWith('/') || url.StartsWith("//", StringComparison.Ordinal)) return false;
        int colon = url.IndexOf(':', StringComparison.Ordinal);
        int slash = url.IndexOf('/', StringComparison.Ordinal);
        // A colon before the first slash is a scheme; after it, it is just an odd but legal path character.
        return colon < 0 || (slash >= 0 && slash < colon);
    }

    /// <summary>
    /// Every element Markdig can emit from the pipeline above. The check below is an allowlist rather than a
    /// list of dangerous tags because an allowlist cannot be outflanked by a tag nobody thought of:
    /// <c>svg</c>, <c>base</c>, <c>style</c> and <c>link</c> are all as dangerous as <c>script</c> here, and
    /// listing what is permitted means a future extension that emits something new degrades loudly instead of
    /// arriving unnoticed.
    /// </summary>
    private static readonly HashSet<string> AllowedElements = new(StringComparer.OrdinalIgnoreCase)
    {
        "a", "blockquote", "br", "code", "col", "colgroup", "dd", "del", "div", "dl", "dt", "em",
        "h1", "h2", "h3", "h4", "h5", "h6", "hr", "img", "input", "ins", "li",
        "mark", "ol", "p", "pre", "section", "strong", "sub", "sup",
        "table", "tbody", "td", "th", "thead", "tr", "ul"
    };

    /// <summary>
    /// Every attribute Markdig writes from this pipeline. Attribute names are checked rather than searched
    /// for by keyword because the values of <c>alt</c> and <c>title</c> are document text: a README whose
    /// image caption happens to read <c>onerror=</c> must not be mistaken for one carrying a handler.
    ///
    /// <para>
    /// <c>style</c> is deliberately absent. Graft's policy forbids inline styles, so an attribute that
    /// reached the browser would be refused there anyway, and the table alignment Markdig would express that
    /// way is converted to a class before rendering. Leaving it out means a future extension that starts
    /// emitting styles degrades visibly here rather than being dropped silently by the browser.
    /// </para>
    /// </summary>
    private static readonly HashSet<string> AllowedAttributes = new(StringComparer.OrdinalIgnoreCase)
    {
        "align", "alt", "checked", "class", "colspan", "disabled", "href", "id", "rel",
        "rowspan", "span", "src", "start", "target", "title", "type", "width"
    };

    /// <summary>One complete tag: its name and its attribute region. Angle brackets in document text are
    /// escaped by the renderer, so every <c>&lt;</c> in the output begins markup it produced itself, and a
    /// <c>&gt;</c> cannot appear inside an attribute value without being escaped first.</summary>
    [GeneratedRegex(@"<\s*/?\s*(?<name>[a-zA-Z][a-zA-Z0-9]*)(?<attributes>[^>]*)>")]
    private static partial Regex Elements();

    /// <summary>One attribute inside a tag, with or without a value.</summary>
    [GeneratedRegex("""^\s*(?<name>[a-zA-Z][a-zA-Z0-9-]*)(?:\s*=\s*"(?<value>[^"]*)")?""")]
    private static partial Regex Attribute();

    /// <summary>An executable or inline scheme. Only ever applied to an attribute that is actually a URL.
    /// </summary>
    [GeneratedRegex(@"^\s*(?:javascript|vbscript|data|file|blob)\s*:", RegexOptions.IgnoreCase)]
    private static partial Regex ExecutableScheme();

    /// <summary>
    /// Fails closed. Markdig with HTML disabled should produce nothing this rejects, so a hit means the
    /// parser changed shape underneath us and the safe answer is to stop rendering markup entirely. It is an
    /// allowlist of elements and attributes rather than a search for dangerous ones, because an allowlist
    /// cannot be outflanked by a tag nobody thought of — <c>svg</c>, <c>base</c>, <c>style</c> and
    /// <c>link</c> are each as dangerous here as <c>script</c>.
    /// </summary>
    private static bool IsClean(string html)
    {
        MatchCollection elements = Elements().Matches(html);

        // Every '<' the renderer writes opens a tag and one in document text is escaped, so a '<' this
        // pattern did not consume is markup of a shape the rest of this method cannot reason about.
        if (elements.Count != html.AsSpan().Count('<')) return false;

        foreach (Match element in elements)
        {
            if (!AllowedElements.Contains(element.Groups["name"].Value)) return false;
            if (!AreAttributesClean(element.Groups["attributes"].Value)) return false;
        }
        return true;
    }

    /// <summary>
    /// Walks a tag's attribute region. The region has to be consumed entirely: anything left over is a shape
    /// this does not understand, and the only safe reading of that is to reject the document.
    /// </summary>
    private static bool AreAttributesClean(string region)
    {
        int at = 0;
        while (at < region.Length)
        {
            // A self-closing tag ends in "/", which is not an attribute but is legitimate output.
            if (region.AsSpan(at).Trim() is { Length: 0 } or "/") return true;

            Match attribute = Attribute().Match(region[at..]);
            if (!attribute.Success) return false;
            at += attribute.Length;

            string name = attribute.Groups["name"].Value;
            if (!AllowedAttributes.Contains(name)) return false;
            bool isUrl = name.Equals("href", StringComparison.OrdinalIgnoreCase)
                || name.Equals("src", StringComparison.OrdinalIgnoreCase);
            if (isUrl && ExecutableScheme().IsMatch(attribute.Groups["value"].Value)) return false;
        }
        return true;
    }

    private static string Escape(string text) =>
        "<pre>" + System.Net.WebUtility.HtmlEncode(text) + "</pre>";
}
